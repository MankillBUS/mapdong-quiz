// ── 현재 언어 ──────────────────────────────────────────────────
let _currentLang = 'ko';

// ── t(key) — 번역 키로 텍스트 반환 ─────────────────────────────
function t(key) {
  return (MALL_I18N[_currentLang] || MALL_I18N.ko)[key]
      || MALL_I18N.ko[key]
      || key;
}

// ── applyLang(lang) — DOM 전체 텍스트 즉시 교체 ────────────────
function applyLang(lang) {
  _currentLang = lang;

  // data-i18n="key" → textContent 교체
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' && el.type !== 'submit') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });

  // data-i18n-ph="key" → placeholder만 교체
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });

  // 번역 버튼 active 토글 (헤더 + 관리자 패널 모두)
  document.querySelectorAll('.tbtn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });

  // 관리자 패널이 열려있으면 현재 페이지 재렌더링
  const adminEl = document.getElementById('page-admin');
  if (adminEl && adminEl.style.display === 'block' &&
      typeof AdminPanel !== 'undefined' && AdminPanel._renderPage) {
    AdminPanel._renderPage(AdminPanel._currentPage || 'dashboard');
  }

  // 재방문 시 언어 유지
  try { localStorage.setItem('mall_lang', lang); } catch(e) {}
}

// ── 초기 언어 복원 ──────────────────────────────────────────────
(function initLang() {
  try {
    const saved = localStorage.getItem('mall_lang') || 'ko';
    if (MALL_I18N[saved]) {
      _currentLang = saved;
      // DOM 준비 후 적용
      if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => applyLang(saved));
      } else {
        applyLang(saved);
      }
    }
  } catch(e) { _currentLang = 'ko'; }
})();
